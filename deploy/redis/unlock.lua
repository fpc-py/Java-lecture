-- ============================================================
-- unlock.lua · 为什么"释放锁"必须是一个 Lua 脚本（ch07 §3.2）
--
-- ⚠️ 本仓库的 Java 代码**不使用**这个脚本 —— 用的是 Redisson 的 RLock，
--    它在内部执行的正是与此等价的 Lua。这个文件的教学价值在于：
--    把 Redisson 藏起来的那一步摊开看，才知道"直接 DEL"错在哪。
--
-- 反面写法（几乎所有分布式锁事故都从这里开始）：
--
--     if (redis.get(key) == myValue) {   -- ① 检查和删除不是原子的
--         redis.del(key);                -- ② 这两行之间锁可能已过期并被别人持有
--     }
--
-- 事故时序（ch07 场景 A，超卖 37 件的真正成因）：
--
--     T0  A 加锁，value=A，锁 TTL 10s
--     T1  A 的业务跑了 12s（超过 TTL），锁在 TTL 到期时被 Redis 自动删除
--     T2  B 加锁成功，value=B，开始自己的业务
--     T3  A 终于跑完，进入 finally，校验 get(key)==A 成立吗？不成立 → 跳过删除
--         —— 但如果代码里没写这个校验（直接 del），A 就把 B 的锁删了
--     T4  C 加锁成功，和 B 同时进入临界区 → 两个线程同时扣库存
--
-- 注意：即使写了校验（①②之间），只要不是原子操作，A 仍可能在
--      "校验通过" 之后、"del 执行" 之前被 TTL 清掉，B 拿到锁，
--      然后 A 的 del 删掉了 B 的锁。窗口很窄，但秒杀场景下必然被踩中。
--
-- 正确写法就是下面这三行：把"比较"和"删除"放进同一个 Lua 脚本。
-- Redis 单线程执行 Lua，脚本内不会有其它命令插入。
--
-- 用法（仅用于理解 / 排障时手工释放）：
--   redis-cli -p 16379 --eval deploy/redis/unlock.lua lock:stock:{90001} , <持有者标识>
--     KEYS[1] = 锁 key
--     ARGV[1] = 持有者标识（Redisson 用的是 "UUID:threadId"）
--
-- 返回值：
--   1 = 锁归你，已删除
--   0 = 锁不归你（已过期 / 被别人持有），什么都没做
--
-- 为什么返回 0 而不是报错：释放锁时的"锁已不属于我"是**正常情况**，
-- 说明业务超时了、锁自然过期了。这时候该记一条 WARN 并继续，
-- 不该抛异常打断 finally —— 否则一个超时会把异常链盖掉，
-- 排查时只看到"释放锁失败"，看不到真正的"业务超时"。
-- ============================================================

if redis.call('GET', KEYS[1]) == ARGV[1] then
    return redis.call('DEL', KEYS[1])
else
    return 0
end
